--   · 이관하며 교정한 결함 3건:
--       (1) 멱등장치 부재 → 더블클릭이면 같은 주문에 2건. v2 는 (order_id, receipt_type)
--           부분 유니크(status<>'cancelled')로 봉쇄하고 경합 시 승자 행을 재생한다.
--       (2) 현금영수증을 business_number='-' / company_name='현금영수증' 문자열로 구분 →
