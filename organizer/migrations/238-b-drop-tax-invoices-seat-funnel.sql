-- ── seat_funnel_events (mig148) ──
-- 좌석 선택 퍼널 텔레메트리. `internal_commerce_read.py` 가 seat-analytics 응답의
-- `funnel` 을 None 으로 하드코딩하며 "테이블 미존재 — 별도 신설"이라 남겨 둔 그 테이블이라,
