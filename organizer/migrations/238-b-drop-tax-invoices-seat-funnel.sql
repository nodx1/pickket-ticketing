--   · 집계: GET  /internal/events/{id}/seat-funnel  (COUNT DISTINCT session_id)
--   · 멱등키가 없는 것이 의도다 — 집계가 DISTINCT session_id 라 중복 수집이 결과를 바꾸지 않는다.
