/**
 * 티켓 화면이 **라이브로 바뀌는 조건**.
 *
 * ## 🔴 왜 함수로 빼는가
 * 잘못하면 **입장한 사람이 QR 을 못 찾는다.** 초대권 분기와 유료 분기 **두 곳**이
 * 같은 판정을 써야 하는데, 각자 적으면 한쪽만 고쳐져 갈린다.
 *
 * ## 🔴 `checked_in_at` 으로 판정하지 않는다
 * 주중권은 목·금 **이틀**이다. `checked_in_at` 은 티켓당 하나의 시각이라
 * 1일차에 입장하면 그 값이 남고, **2일차에 QR 이 사라진다.**
 * v2 가 `admitted_today`(KST 오늘 날짜의 입장 기록 존재 여부)를 따로 내려준다.
 *
 * ## ⚠️ 세 값을 구분한다
 * ```
 * true       오늘 입장했다        → 라이브
 * false      아직 입장 전이다      → QR
 * undefined  v2 구버전이라 모른다  → 🔴 QR (모르면 안 바꾼다)
 * ```
 * `undefined` 를 truthy 검사로 흘리면 **아직 입장도 안 한 사람의 QR 이 사라진다.**
 * 게이트 앞에서 QR 을 못 찾는 것이 이 화면에서 가장 나쁜 사고다.
 */

/**
 * 라이브 화면으로 바꿀 것인가. **`true` 하나만 통과한다.**
 *
 * ⚠️ 인자로 **티켓을 통째로** 받는다. 호출부가 필드를 골라 넘기면 거기서 `checked_in_at`
 *    을 넣는 실수가 나고, 그 실수는 **2일차 아침 게이트 앞에서만** 드러난다.
 *    필드를 고르는 곳을 이 파일 하나로 못 박는다.
 */
export function shouldShowLive(ticket: {
  admitted_today?: boolean | null;
  checked_in_at?: string | null;
}): boolean {
  return ticket.admitted_today === true;
}

