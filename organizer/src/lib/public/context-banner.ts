/**
 * 공개 랜딩 최상단 안내 배너 — **주최자가 쓴 문구만** 표시한다.
 *
 * ## 🔴 왜 자동 생성을 걷어냈나 (2026-07-30 주최측 피드백)
 *
 * 종전에는 배너 API 가 `D-N · 날짜 · 잔여석 · 최저가` 를 **스스로 계산**해 표시했고,
 * 설정 화면의 「상단 안내 배너」(500자 입력칸)에 주최자가 써넣은 값은 **읽지 않았다.**
 * 저장은 정상이었다 — 화면에만 안 나왔다.
 *
 * 그 결과 두 가지가 동시에 일어났다:
 *  1. 주최자가 쓴 문구가 사라진다("얼리버드 20% 할인" 같은 실제 공지)
 *  2. 통제할 수 없는 자동 문구가 최상단에 뜬다 — KLPGA 에서 **`₩0부터`** 가 나왔다.
 *     최저가 계산에 **0원 등급**(초대권용 comp)이 섞여, 유료 대회가 무료로 보였다.
 *
 * 주최측이 "보라색 바 삭제 필요" 라고 한 그 띠다. 끄는 것이 정답이 아니라,
 * **주최자가 통제하게** 하는 것이 정답이다 — 입력칸은 이미 있었다.
 *
 * ⟹ 이제 문구를 비우면 배너가 사라지고, 쓰면 그것이 나온다. 코드 배포가 필요 없다.
 *
 * 📌 남은 부채: 0원 등급이 최저가에 섞이는 계산 결함은 **배너 밖에도 영향**을 준다
 *    (마켓 목록·검색 결과 등 다른 최저가 소비처). 별건으로 조사해야 한다.
 */

/** 배너 문구 최대 길이 — 저장 zod(`api/events/[eventId]/route.ts`)와 같은 값. */
export const CONTEXT_BANNER_MAX = 500;

/**
 * 주최자가 입력한 배너 문구를 표시용으로 정규화한다.
 *
 * 공백만 남은 값은 **배너 해제**로 취급한다 — 스페이스 하나 때문에 빈 띠가 뜨면
 * "왜 안 지워지지" 가 된다.
 */
export function resolveContextBanner(raw: unknown): string | null {
  if (typeof raw !== "string") return null;
  const trimmed = raw.trim();
  if (trimmed === "") return null;
  return trimmed.slice(0, CONTEXT_BANNER_MAX);
}

/**
 * 배너 캐시 키 — 조회 API 와 무효화 지점이 **같은 문자열**을 쓰도록 한 곳에 둔다.
 * 종전처럼 양쪽에 리터럴을 적으면 한쪽만 바뀌었을 때 캐시가 영원히 안 지워진다.
 */
export function contextBannerCacheKey(eventId: string): string {
  return `ctxbanner:${eventId}`;
}
