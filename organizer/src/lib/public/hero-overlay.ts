/**
 * 히어로 오버레이 표시 판정 — 제목·배지 + 가독성 어둠막을 이미지 위에 얹을지.
 *
 * 🔴 왜 끌 수 있어야 하나
 * 완성형 포스터(제목·날짜가 이미 인쇄된 이미지)에는 오버레이가 **중복이자 훼손**이다.
 * 특히 가독성용 어둠막(`rgba(0,0,0,0.28)` ~ `0.92`)이 **흰 배경을 회색으로 만든다** —
 * 실측: 이미지 RGB(255,255,253) → 화면 RGB(195,196,196).
 * 주최자가 흰 배경 포스터를 올렸는데 회색으로 게시되면 브랜드가 훼손된다.
 *
 * 판정을 순수 함수로 둔 이유: 이 값은 서버 컴포넌트 안에서 쓰여 테스트가 닿지 못한다.
 * 기본값이 뒤집히면 **기존 모든 행사의 히어로가 한꺼번에 바뀐다** — 회귀로 고정한다.
 */

/** 미설정·잘못된 값은 **켬**(현행 유지). 끄는 건 명시적으로 `false` 일 때만. */
export function showsHeroOverlay(raw: unknown): boolean {
  return raw !== false;
}
