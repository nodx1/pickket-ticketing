/* ── Public API ───────────────────────────────────────────────────────── */

/** Check if a tier ID was generated by our fallback generator. */
export function isDemoTier(tierId: string): boolean {
  return tierId.startsWith("demo-tier-");
}

/** Check if a venue was generated by our fallback generator. */
export function isFallbackVenue(venueId: string): boolean {
  return venueId.startsWith("fb-");
}

/** UUID v4 pattern for real events. */
const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Single checkpoint that ensures tiers and venue are always populated.
 *
 * Call this ONCE after all API calls complete (or fail). It fills any gaps
 * with deterministic fallback data when appropriate, eliminating the need
 * for scattered isDemoTier / buildFallback* checks throughout the page.
 *
 * Rules:
 * - If tiers are empty → inject fallback tiers (makes them "demo" tiers)
 * - If venue is null AND we're in demo mode → inject fallback venue
 * - "Demo mode" = non-UUID eventId OR tiers[0] is a demo tier
 */
export function ensureFallbackData(
  eventId: string,
  eventData: EventDetail | null,
  tiers: SeatTier[],
  venue: VenueData | null,
): { event: EventDetail; tiers: SeatTier[]; venue: VenueData | null } {
  // Ensure we always have an event object to derive fallback data from
  const event: EventDetail =
    eventData ??
    ({
      id: eventId,
      title: "이벤트",
      status: "bidding_open",
    } as EventDetail);

  // Ensure tiers exist
  const effectiveTiers = tiers.length > 0 ? tiers : buildFallbackTiers(event);

  // Determine if we're in demo/fallback mode
  const isReal = UUID_RE.test(eventId);
  const hasDemoTiers =
    effectiveTiers.length > 0 && isDemoTier(effectiveTiers[0].id);
  const hasAssignedSeating = effectiveTiers.some(
    (t) => t.seating_type === "assigned",
  );
  const needsFallback = !isReal || hasDemoTiers;
  const needsVenueFallback = needsFallback || (hasAssignedSeating && !venue);

  // Ensure venue for demo scenarios or real events with assigned seating but no venue
  const effectiveVenue =
    venue ?? (needsVenueFallback ? buildFallbackVenue(event) : null);

  return { event, tiers: effectiveTiers, venue: effectiveVenue };
}

/**
 * Build fallback tiers for a demo event.
 * Moves the existing inline logic from EventDetailClient and
 * sets `seating_type: "assigned"` so the seat-selection UI activates.
 */
export function buildFallbackTiers(event: EventDetail): SeatTier[] {
  if (!event?.id) return [];
  const min = event.min_price ?? 50000;
  const max = event.max_price ?? min * 2.5;
  const total = event.total_seats ?? 1000;
  const opens = event.bidding_opens_at;
  const closes = event.bidding_closes_at;

  const presets = [
    { name: "VIP", pctPrice: 1.0, pctSeats: 0.08, mode: "fixed_fcfs" },
    { name: "R석", pctPrice: 0.75, pctSeats: 0.15, mode: "fixed_fcfs" },
    { name: "S석", pctPrice: 0.5, pctSeats: 0.3, mode: "fixed_fcfs" },
    { name: "A석", pctPrice: 0.25, pctSeats: 0.3, mode: "fixed_fcfs" },
    { name: "B석", pctPrice: 0.0, pctSeats: 0.17, mode: "fixed_fcfs" },
  ];

  return presets.map((p, i) => {
    const basePrice =
      Math.round((min + (max - min) * p.pctPrice) / 1000) * 1000;
    const capacity = Math.max(Math.round(total * p.pctSeats), 10);
    const soldCount = Math.round(capacity * (0.35 + i * 0.08));
    return {
      id: `demo-tier-${event.id}-${i}`,
      event_id: event.id,
      name: p.name,
      capacity,
      total: capacity,
      base_price: basePrice,
      sale_mode: p.mode,
      face_price: basePrice,
      sold_count: soldCount,
      remaining: capacity - soldCount,
      min_price: basePrice,
      max_price_cap: Math.round(basePrice * 1.5),
      bidding_opens_at: opens,
      bidding_closes_at: closes,
      seating_type: "assigned",
      max_group_size: 4,
    } as SeatTier;
  });
}

/**
 * Build a fallback venue (1000×750 concert hall with 5 sections).
 * The venue name is taken from the event for display purposes.
 */
export function buildFallbackVenue(event: EventDetail): VenueData {
  const venueName =
    (event as EventDetail & { venue?: string }).venue ??
    event.title ??
    "Demo Venue";
  const venueId = deterministicId(`venue-${event.id}`);

  const sections: VenueSectionData[] = SECTION_DEFS.map((def) => ({
    id: deterministicId(`section-${event.id}-${def.name}`),
    venue_id: venueId,
    name: def.name,
    label: def.label,
    capacity: def.capacity,
    svg_path: def.svg_path,
    center_x: def.center_x,
    center_y: def.center_y,
    floor: def.floor,
    color: def.color,
    view_image_url: null,
  }));

  return {
    id: venueId,
    name: venueName,
    city:
      (event as EventDetail & { location_city?: string }).location_city ??
      "서울",
    address: "",
    total_capacity: SECTION_DEFS.filter((d) => d.name !== "__stage__").reduce(
      (sum, d) => sum + d.capacity,
      0,
    ),
    map_svg_url: null,
    map_width: 800,
    map_height: 440,
    thumbnail_url: null,
    seating_chart_url: null,
    sections,
  };
}

/**
 * Build deterministic fallback seats for a given tier + venue.
 * Generates seats for ALL venue sections so VenueMap shows availability
 * colors for every section, not just the tier's primary section.
 */
export function buildFallbackSeatsForTier(
  tier: SeatTier,
  venue: VenueData,
): SeatData[] {
  const seats: SeatData[] = [];
  for (const section of venue.sections) {
    if (section.name === "__stage__") continue;
    const capacity = Math.min(section.capacity, 100); // cap at 100 for perf
    seats.push(...buildFallbackSeats(tier.id, section.name, capacity));
  }
  return seats;
}

/**
 * Generate deterministic seats for a section.
 * - Seats per row: 10-20 depending on capacity
 * - Sold ratio: derived from tierId hash (35-67%)
 * - Quality score: higher for center + front rows
 */
export function buildFallbackSeats(
  tierId: string,
  sectionName: string,
  capacity: number,
): SeatData[] {
  const seatsPerRow = Math.max(10, Math.min(20, Math.floor(capacity / 8)));
  const numRows = Math.ceil(capacity / seatsPerRow);
  const soldRatio = 0; // 데모: 매진 좌석 없음

  const seats: SeatData[] = [];

  for (let row = 1; row <= numRows; row++) {
    const seatsInRow =
      row < numRows ? seatsPerRow : capacity - (numRows - 1) * seatsPerRow;

    for (let seat = 1; seat <= seatsInRow; seat++) {
      const seatSeed = `${tierId}-${sectionName}-${row}-${seat}`;
      const hash = simpleHash(seatSeed);

      // Quality: front rows + center seats score higher
      const rowScore = 1 - (row - 1) / numRows;
      const centerScore =
        1 - Math.abs(seat - (seatsInRow + 1) / 2) / (seatsInRow / 2);
      const qualityScore =
        Math.round((rowScore * 0.6 + centerScore * 0.4) * 100) / 100;

      // Status: deterministic based on hash + sold ratio
      const isSold = hash < soldRatio;

      seats.push({
        id: deterministicId(seatSeed),
        section: sectionName,
        row_number: row,
        seat_number: seat,
        is_obstructed: false,
        x: seat * 40,
        y: row * 40,
        label: `${sectionName} ${row}열 ${seat}번`,
        status: isSold ? "sold" : "available",
        tier_id: tierId,
        quality_score: qualityScore,
      });
    }
  }

  return seats;
}
